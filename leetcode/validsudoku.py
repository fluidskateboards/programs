class Solution:
    def isValidSudoku(self, board):
        con1 = True
        con2 = True
        con3 = True
        for i in range(9):
            a = set()
            for j in range(9):
                if board[i][j] in a:
                    con1 = False
                    break
                elif board[i][j] != ".":
                    a.add(board[i][j])
        for j in range(9):
            b = set()
            for i in range(9):
                if board[i][j] in b:
                    con2 = False
                    break
                elif board[i][j] != ".":
                    b.add(board[i][j])
        for x in range(3):
            for y in range(3):
                third = set()
                for i in range(3):
                    r = (x*3) + i
                    for j in range(3):
                        c = (y*3) + j
                        if board[r][c] in third:
                            con3 = False
                            break
                        elif board[r][c] != ".":
                            third.add(board[r][c])
        print("rows: " + str(con1) + "  cols: " + str(con2) + " 3x3: " + str(con3))
        return con1 and con2 and con3

        

